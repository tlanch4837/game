# Converts the SPIR-V that spirv.bat makes into Metal Shading Language for the iOS Metal backend (renderer_metal.mm).
# msl.bat runs it; see docs/metal_backend.md for the binding scheme. Fails (exit 1) if any shader does not convert or
# breaks the binding rules below.
#
# Binding scheme (must match renderer_metal.mm, namespace mtlslot):
#   * Vulkan descriptor set 0 stays discrete: binding N becomes [[buffer(N)]] / [[texture(N)]] / [[sampler(N)]]
#     (--msl-decoration-binding), so the backend binds exactly the numbers the Vulkan backend writes.
#   * Vulkan descriptor set 1 (the mesh material: albedo, normal, sampler, surface, extra) becomes a Metal argument buffer
#     at [[buffer(1)]], members [[id(binding)]] (--msl-argument-buffers, tier 1 encoding, every member always declared).
#   * Push constants (mesh pc, ui pc, compute pc, water wc) are rewritten to [[buffer(29)]].
#   * Vertex streams are not shader resources: the backend's vertex descriptors use buffers 30 (stream 0) and 28 (stream 1).
#   * Entry points are renamed to the output file's stem (mesh_vs, post_taa_ps, ...) so every .metal links into one
#     default.metallib without name clashes.
param([Parameter(Mandatory = $true)][string]$SpvDir, [Parameter(Mandatory = $true)][string]$OutDir)
$ErrorActionPreference = 'Stop'
$cross = Join-Path $env:VULKAN_SDK 'Bin\spirv-cross.exe'
if (-not (Test-Path $cross)) { Write-Error "spirv-cross not found at $cross"; exit 1 }
New-Item -ItemType Directory -Force $OutDir | Out-Null

# stem, SPIR-V entry, stage. Mirrors spirv.bat; post_ao_rt_ps (ray query AO) is skipped: Metal uses the non-RT AoPS.
$shaders = @(
    'mesh_vs VSMain vert', 'mesh_ps PSMain frag', 'mesh_overlay_ps PSOverlay frag',
    'post_vs FullscreenVS vert', 'post_ao_ps AoPS frag', 'post_clouds_ps CloudsPS frag', 'post_composite_ps CompositePS frag',
    'post_taa_ps TaaPS frag', 'post_tonemap_ps TonemapPS frag', 'post_cloudshadow_ps CloudShadowPS frag',
    'post_cloudresolve_ps CloudResolvePS frag', 'post_probetrace_ps ProbeTracePS frag', 'post_probeblend_ps ProbeBlendPS frag',
    'post_exposure_ps ExposurePS frag', 'post_bloom_ps BloomPS frag',
    'mesh_shadow_vs ShadowVS vert', 'mesh_inst_vs VSInstanced vert', 'mesh_shadow_inst_vs ShadowInstancedVS vert',
    'selftest_vs FullscreenVS vert', 'selftest_fill_ps FillPS frag', 'selftest_sample_ps SamplePS frag',
    'mesh_veg_vs VSVegetation vert', 'mesh_shadow_veg_vs ShadowVegetationVS vert',
    'mesh_shadow_cut_vs ShadowCutoutVS vert', 'mesh_shadow_cut_ps PSShadowCutout frag',
    'vegetation_CSReset CSReset comp', 'vegetation_CSPlace CSPlace comp', 'vegetation_CSArgs CSArgs comp',
    'water_CSRipple CSRipple comp', 'water_CSWaves CSWaves comp', 'water_CSSky CSSky comp',
    'water_vs WaterVS vert', 'water_ps WaterPS frag',
    'mesh_motion_ps PSMainMotion frag', 'mesh_skinned_motion_vs VSSkinnedMotion vert',
    'mesh_veg_depth_vs VSVegetationDepth vert', 'mesh_veg_depth_ps PSVegetationDepth frag', 'mesh_veg_shade_ps PSVegetationShade frag',
    'ui_vs UiVS vert', 'ui_ps UiPS frag')

$failed = 0
foreach ($line in $shaders) {
    $stem, $entry, $stage = $line -split ' '
    $spv = Join-Path $SpvDir "$stem.spv"
    $out = Join-Path $OutDir "$stem.metal"
    if (-not (Test-Path $spv)) { Write-Host "MISSING $spv"; $failed++; continue }
    $xargs = @($spv, '--msl', '--msl-ios', '--msl-version', '20300', '--msl-decoration-binding',
        '--msl-argument-buffers', '--msl-argument-buffer-tier', '0', '--msl-discrete-descriptor-set', '0',
        '--msl-force-active-argument-buffer-resources',
        '--rename-entry-point', $entry, $stem, $stage, '--output', $out)
    & $cross @xargs
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $out)) { Write-Host "FAILED $stem"; $failed++; continue }
    $text = Get-Content $out -Raw
    # Push constants to the fixed slot.
    $text = [regex]::Replace($text, '(constant type_PushConstant_\w+& \w+) \[\[buffer\(\d+\)\]\]', '$1 [[buffer(29)]]')
    $text = "// Generated by tools/msl.ps1 (msl.bat) from src/shaders via SPIR-V; do not edit. Entry: $entry ($stage).`n" + $text
    [System.IO.File]::WriteAllText($out, $text.Replace("`r`n", "`n"))
    # Binding rules.
    foreach ($m in [regex]::Matches($text, '(\w+)& (\w+) \[\[buffer\((\d+)\)\]\]|(\w+) (\w+) \[\[buffer\((\d+)\)\]\]')) {
        $n = [int]($m.Groups[3].Value + $m.Groups[6].Value)
        if ($n -eq 28 -or $n -eq 30) { Write-Host "BINDING $stem uses buffer($n), reserved for vertex streams"; $failed++ }
        if ($n -eq 29 -and $m.Value -notmatch 'PushConstant') { Write-Host "BINDING $stem puts a non-push-constant at buffer(29)"; $failed++ }
    }
    if ($text -match 'PushConstant' -and $text -notmatch '\[\[buffer\(29\)\]\]') { Write-Host "BINDING $stem push constant not at 29"; $failed++ }
    foreach ($m in [regex]::Matches($text, '\[\[texture\((\d+)\)\]\]')) { if ([int]$m.Groups[1].Value -gt 30) { Write-Host "BINDING $stem texture index > 30"; $failed++ } }
    foreach ($m in [regex]::Matches($text, '\[\[sampler\((\d+)\)\]\]')) { if ([int]$m.Groups[1].Value -gt 15) { Write-Host "BINDING $stem sampler index > 15"; $failed++ } }
}
if ($failed) { Write-Host "$failed shader problem(s)"; exit 1 }
Write-Host "Converted $($shaders.Count) shaders to $OutDir"
exit 0
