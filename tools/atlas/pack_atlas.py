"""Packs building textures into shared atlas pages (docs/building_atlas.md).

    python tools/atlas/pack_atlas.py [--manifest tools/atlas/building_atlas_pages.json] [--check]

Rerunnable: edit a source texture or the manifest, run it again. Pages whose inputs did not change are skipped
(their content hash matches), so a rebuild only rewrites what moved. --check packs nothing and exits 1 when a page is
out of date (for a build step).

For every page in the manifest it writes, into the manifest's "out" folder:
  <page>_albedo.png    RGBA8, 4096 x 4096: rgb = albedo (sRGB, as authored), a = roughness (0..255)
  <page>_normal.png    RGBA8, 4096 x 4096: rgb = tangent-space normal, a = height (255 high)
  building_atlas.json  the table the generators and the engine read: cells by name -> page, index, metres per tile
and src/shaders/building_atlas.hlsli, the layout constants mesh.hlsl samples with.

Layout. An 8 x 8 grid of 512 px cells. Each cell holds one tile of its texture, resampled to 480 px, wrapped 16 px
past every edge (np.pad mode="wrap"), so a sample anywhere in the 480 px interior, and the bilinear and anisotropic
footprint around it, reads the tile's own continuation. The cells are 512-aligned, so the engine's 2 x 2 box mips keep
every cell's texels apart down to mip 8 (16 px pad = one texel at mip 4); the shader caps its level of detail at 4,
so no mip it reads ever blends two cells. No mips are written: the engine makes them on upload, and those are per cell.
"""
import argparse
import hashlib
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SIZE, GRID, CELL, PAD = 4096, 8, 512, 16
INNER = CELL - 2 * PAD
MAX_LOD = 4  # log2(PAD): the deepest mip whose bilinear footprint stays inside a cell
FORMAT = 1   # bump when the layout or channel meaning changes


def rel(p):
    return os.path.join(ROOT, p) if not os.path.isabs(p) else p


def file_hash(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def page_hash(page, defaults):
    """Everything a page's pixels depend on: the layout, its cells' parameters and the bytes of every source file."""
    h = hashlib.sha256()
    h.update(json.dumps({"format": FORMAT, "size": SIZE, "grid": GRID, "cell": CELL, "pad": PAD}, sort_keys=True).encode())
    for c in page["cells"]:
        c = {**defaults, **c}
        h.update(json.dumps({k: c[k] for k in sorted(c)}, sort_keys=True).encode())
        for key in ("albedo", "normal", "height"):
            if c.get(key):
                h.update(file_hash(rel(c[key])).encode())
    return h.hexdigest()


def load_tile(path, mode):
    im = Image.open(rel(path)).convert(mode)
    if im.size != (INNER, INNER):
        im = im.resize((INNER, INNER), Image.LANCZOS)
    return np.asarray(im)


def wrap(tile):
    return np.pad(tile, ((PAD, PAD), (PAD, PAD), (0, 0)), mode="wrap")


def pack_page(page, defaults):
    albedo = np.zeros((SIZE, SIZE, 4), np.uint8)
    normal = np.zeros((SIZE, SIZE, 4), np.uint8)
    albedo[..., 3] = 217  # unused cells: rough
    normal[..., :3] = (128, 128, 255)
    normal[..., 3] = 255
    for index, cell in enumerate(page["cells"]):
        c = {**defaults, **cell}
        a = load_tile(c["albedo"], "RGB")
        n = load_tile(c["normal"], "RGB") if c.get("normal") else np.full((INNER, INNER, 3), (128, 128, 255), np.uint8)
        if c.get("height"):
            h = load_tile(c["height"], "L")
        else:  # no height map: the albedo's own luminance, stretched, stands in (cavity only; never displaces)
            lum = a.astype(np.float32) @ np.array([0.2126, 0.7152, 0.0722], np.float32)
            lo, hi = np.percentile(lum, 2), np.percentile(lum, 98)
            h = np.clip((lum - lo) / max(hi - lo, 1.0) * 255.0, 0, 255).astype(np.uint8)
        rough = np.full((INNER, INNER), int(round(np.clip(c["roughness"], 0.0, 1.0) * 255)), np.uint8)
        x, y = (index % GRID) * CELL, (index // GRID) * CELL
        albedo[y:y + CELL, x:x + CELL] = wrap(np.dstack([a, rough]))
        normal[y:y + CELL, x:x + CELL] = wrap(np.dstack([n, h]))
    return albedo, normal


def write_hlsli(path, table_hash):
    text = f"""// Generated by tools/atlas/pack_atlas.py; do not edit. The shared building atlas's layout (docs/building_atlas.md), the same for
// every page: which page a draw samples is the material it binds, which cell is the vertex alpha (3 + (cell + 0.5) / 64).
// Table hash {table_hash[:16]}.
#ifndef TBD_BUILDING_ATLAS_HLSLI
#define TBD_BUILDING_ATLAS_HLSLI
static const float kAtlasSize = {SIZE}.0;    // texels across a page
static const float kAtlasGrid = {GRID}.0;      // cells across
static const float kAtlasPad = {PAD / CELL!r}; // the wrapped border, as a fraction of a cell
static const float kAtlasMaxLod = {MAX_LOD}.0;   // the deepest mip that never mixes two cells
#endif
"""
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=os.path.join(ROOT, "tools", "atlas", "building_atlas_pages.json"))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    manifest = json.load(open(args.manifest, encoding="utf-8"))
    out = rel(manifest["out"])
    os.makedirs(out, exist_ok=True)
    defaults = manifest.get("defaults", {})
    table_path = os.path.join(out, "building_atlas.json")
    old = json.load(open(table_path, encoding="utf-8")) if os.path.exists(table_path) else {"pages": []}
    old_hash = {p["name"]: p.get("hash") for p in old.get("pages", [])}

    table = {"format": FORMAT, "size": SIZE, "grid": GRID, "cellPx": CELL, "padPx": PAD, "maxLod": MAX_LOD,
             "alpha": "3 + (index + 0.5) / 64 in the engine; glTF COLOR_0 alpha = (index + 0.5) / 64 on a material named *atlas*",
             "pages": [], "cells": {}}
    stale = []
    for page in manifest["pages"]:
        if len(page["cells"]) > GRID * GRID:
            sys.exit(f"page {page['name']}: {len(page['cells'])} cells, at most {GRID * GRID}")
        h = page_hash(page, defaults)
        files = {"albedo": f"{page['name']}_albedo.png", "normal": f"{page['name']}_normal.png"}
        fresh = old_hash.get(page["name"]) == h and all(os.path.exists(os.path.join(out, f)) for f in files.values())
        if not fresh:
            stale.append(page["name"])
            if not args.check:
                a, n = pack_page(page, defaults)
                Image.fromarray(a, "RGBA").save(os.path.join(out, files["albedo"]), optimize=False, compress_level=6)
                Image.fromarray(n, "RGBA").save(os.path.join(out, files["normal"]), optimize=False, compress_level=6)
                print(f"packed {page['name']}: {len(page['cells'])} cells")
        elif args.force and not args.check:
            a, n = pack_page(page, defaults)
            Image.fromarray(a, "RGBA").save(os.path.join(out, files["albedo"]))
            Image.fromarray(n, "RGBA").save(os.path.join(out, files["normal"]))
        table["pages"].append({"name": page["name"], "hash": h, **files, "cells": len(page["cells"])})
        for index, cell in enumerate(page["cells"]):
            c = {**defaults, **cell}
            if c["name"] in table["cells"]:
                sys.exit(f"cell name {c['name']} appears twice")
            table["cells"][c["name"]] = {"page": page["name"], "index": index, "alpha": round((index + 0.5) / 64.0, 6),
                                         "metresPerTile": c["metresPerTile"], "roughness": c["roughness"]}
    table["hash"] = hashlib.sha256("".join(p["hash"] for p in table["pages"]).encode()).hexdigest()
    if args.check:
        print("out of date: " + ", ".join(stale) if stale else "atlas up to date")
        sys.exit(1 if stale else 0)
    with open(table_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(table, f, indent=1)
    write_hlsli(os.path.join(ROOT, "src", "shaders", "building_atlas.hlsli"), table["hash"])
    print(f"{len(table['pages'])} pages, {len(table['cells'])} cells, hash {table['hash'][:16]}" + ("" if stale else " (nothing changed)"))


if __name__ == "__main__":
    main()
