"""Extract the road library from assets/roads/preview.html into assets/roads/roadlib.js (an ES module).
Re-run after editing preview.html so city.html stays in sync."""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / 'assets/roads/preview.html').read_text(encoding='utf-8').splitlines()
start = next(i for i, l in enumerate(src) if l.strip() == '<script type="module">') + 1
end = next(i for i, l in enumerate(src) if '================================================================ scene' in l)
body = [l for l in src[start:end] if not l.startswith('import {OrbitControls}')]
code = '\n'.join(body).replace('`tex/', '`${TEX}')
code = code.replace("import * as THREE from 'three';", "import * as THREE from 'three';\nconst TEX = new URL('./tex/', import.meta.url).href;", 1)
names = ['THREE', 'MAT', 'PROFILES', 'P', 'st', 'lanes', 'Network', 'buildNetworkMeshes', 'buildGpuRoads', 'buildPieces', 'buildDecals',
         'buildJunction', 'junctionMeshes', 'laneConnections', 'approachDecals', 'placeTrafficControl', 'updateSignals', 'at', 'v2']
code += '\nexport {' + ', '.join(n for n in names if n != 'THREE') + '};\n'
(root / 'assets/roads/roadlib.js').write_text('// GENERATED by tools/road_gen/extract_roadlib.py from preview.html. Do not edit.\n' + code, encoding='utf-8')
print('wrote roadlib.js', len(code), 'chars')
