// Width in pixels of `text` at the given pixel size per font cell (6 cells per character).
inline float TextWidth(const std::string& text, float cell) { return (float)text.size() * 6.0f * cell; }

// Appends `len` characters of `text` as quads, one per lit font pixel; (x, y) is the top-left corner. Takes a pointer and
// a length so callers can draw part of a buffer without building a std::string (the GUI does this every frame).
inline void AppendTextN(std::vector<Vertex>& out, float x, float y, float cell, const char* text, size_t len, Vec3 color,
                        bool cased = false) {
    float cx = x;
    for (size_t i = 0; i < len; ++i) {
        if (const detail::Glyph* g = cased ? detail::FindGlyphCased(text[i]) : detail::FindGlyph(text[i])) {
            for (int row = 0; row < 7; ++row)
                for (int col = 0; col < 5; ++col)
                    if (g->rows[row] & (0x10 >> col)) {
                        // Snap to whole pixels so fractional cell sizes stay crisp.
                        const float x0 = std::round(cx + col * cell), x1 = std::round(cx + (col + 1) * cell);
                        const float y0 = std::round(y + row * cell), y1 = std::round(y + (row + 1) * cell);
                        AppendQuad(out, x0, y0, x1, y1, color);
                    }
        }
        cx += 6.0f * cell;
    }
}

// Appends the text as quads, one per lit font pixel. (x, y) is the top-left corner. Lower case draws as capitals.
inline void AppendText(std::vector<Vertex>& out, float x, float y, float cell, const std::string& text, Vec3 color) {
    AppendTextN(out, x, y, cell, text.data(), text.size(), color, false);
}

